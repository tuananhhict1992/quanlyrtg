// AI Studio's ZIP importer omits binary public assets from Cloud Run builds.
// Keep the original PNG intact and package its bytes as a lazy Vite asset chunk.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const data = readFileSync(new URL('public/brand/hict-logo.png', root)).toString('base64');
const dir = new URL('src/assets/hict/', root);
mkdirSync(dir, { recursive: true });
const parts = [];
for (let offset = 0; offset < data.length; offset += 400000) {
  const name = `part${parts.length + 1}`;
  writeFileSync(new URL(`${name}.ts`, dir), `// Generated by scripts/embed-brand-logo.mjs; original PNG bytes.\nexport default '${data.slice(offset, offset + 400000)}';\n`);
  parts.push(name);
}
writeFileSync(new URL('index.ts', dir), parts.map(p => `import ${p} from './${p}';`).join('\n') + `\nexport default 'data:image/png;base64,' + [${parts.join(',')}].join('');\n`);
console.log(`Embedded original logo in ${parts.length} text parts; the PNG is unchanged.`);
